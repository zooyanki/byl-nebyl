def _glyph(rows7, desc=None, h=9):
    rows = _rows(rows7) + (_rows(desc) if desc else [])
    w = max(len(r) for r in rows)
    rows = rows + ["." * w] * (h - len(rows))
    return np.array([[c == "#" for c in r.ljust(w, ".")] for r in rows], dtype=bool)


def _build_body():
    g = {}
    for ch, s in _F57.items():
        g[ch] = _glyph(s)
    for ch, s in _PUNCT.items():
        g[ch] = _glyph(s)
    for ch, (s, d) in _LC.items():
        g[ch] = _glyph(s, d)
    g[" "] = np.zeros((9, 3), bool)
    return {"glyphs": g, "h": 9, "sp": 1, "cap": 7}


FONT_RU = _build_body()


def _ustav(m):
    """7-row capital -> 12-row heading glyph: tall, heavy outer stems (columns
    duplicated) and pointed spires above top stems — a nod to устав/вязь."""
    rowmap = [0, 1, 1, 2, 2, 3, 4, 4, 5, 5, 6]
    s = m[rowmap]
    h, w = s.shape
    if w >= 5:
        last = 4
        colmap = [0, 0] + list(range(1, last)) + [last, last] + list(range(last + 1, w))
    else:
        mid = w // 2
        colmap = list(range(0, mid + 1)) + list(range(mid, w))
    g = s[:, colmap]
    out = np.zeros((h + 1, len(colmap)), bool)
    out[1:] = g
    seen = set()
    for nx, ox in enumerate(colmap):
        if ox in seen:
            continue
        if m[0, ox] and m[1, ox]:
            # spire above the inner pixel of a doubled stem / the stem itself
            dup = [i for i, c in enumerate(colmap) if c == ox]
            tip = dup[-1] if ox == 0 else dup[0]
            out[0, tip] = True
            seen.add(ox)
    return out


def _build_ustav():
    g = {}
    for ch, s in _F57.items():
        if ch == " ":
            continue
        g[ch] = _ustav(_glyph(s, h=7))
    for ch in ("—", "·", "«", "»"):
        g[ch] = _ustav(_glyph(_PUNCT[ch], h=7))
    g[" "] = np.zeros((12, 4), bool)
    return {"glyphs": g, "h": 12, "sp": 1}



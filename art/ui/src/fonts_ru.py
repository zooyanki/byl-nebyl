def _u_glyph(rows, top=None, desc=None, h=14):
    w = max(len(r) for r in rows)
    out = [(top or "").ljust(w, ".")] + [r.ljust(w, ".") for r in rows] + [d.ljust(w, ".") for d in (desc or [])]
    out = out + ["." * w] * (h - len(out))
    return np.array([[c == "#" for c in r] for r in out], dtype=bool)


def _build_ustav_hand():
    g = {}
    for ch, rows in _U.items():
        g[ch] = _u_glyph(rows, desc=_U_DESC.get(ch))
    for ch, (base, top) in _U_TOP.items():
        g[ch] = _u_glyph(_U[base], top=top, desc=_U_DESC.get(base))
    g[" "] = np.zeros((14, 5), bool)
    return {"glyphs": g, "h": 14, "sp": 2, "cap": 11, "top": 1}


